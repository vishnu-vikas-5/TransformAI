/**
 * Universal browser file download helper using Blob and temporary link trigger
 */
export const downloadBlob = (blob, filename) => {
  try {
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    setTimeout(() => {
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }, 150);
  } catch (err) {
    console.error("Browser download failed:", err);
  }
};

/**
 * Generates and triggers download of a Markdown (.md) file
 */
export const exportToMarkdown = (title, rawContent, docId = "document") => {
  const cleanTitle = (title || "document").toLowerCase().replace(/[^a-z0-9]+/g, '_');
  const filename = `${docId}_${cleanTitle}.md`;
  const header = `# ${title}\n*Generated by SyntaxX Agentic Intelligence Engine*\n\n---\n\n`;
  const blob = new Blob([header + (rawContent || "")], { type: "text/markdown;charset=utf-8" });
  downloadBlob(blob, filename);
  return filename;
};

