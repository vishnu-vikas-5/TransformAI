/**
 * Generates and triggers download of high-resolution Infographic Image (PNG or JPG)
 * Uses the exact same 1080x1920 layout engine as the PDF.
 */
export const exportInfographicImage = async (selectedDoc, result, format = 'png') => {
  try {
    const model = result?.structuredInfographic || buildStructuredInfographic(result?.content, result, selectedDoc);
    const intel = extractCoreContentIntelligence(selectedDoc, result);
    const sourceId = selectedDoc?.id || intel?.metadata?.advisoryId || 'document';
    const advisoryId = intel?.metadata?.advisoryId || (sourceId === 'cybersecurity' ? 'CSIRT-2024-38077-ADV' : (sourceId === 'health_advisory' ? 'MOH-PHE-2026-04' : (sourceId === 'research_paper' ? 'RESEARCH-LLM-2026' : 'TAI-ADV-2026-88421')));
    const ext = format.toLowerCase() === 'jpg' ? 'jpg' : 'png';
    const filename = `${advisoryId}_Visual_Infographic.${ext}`;
    
    if (ext === 'jpg') {
      await exportInfographicAsJpg(model, filename);
    } else {
      await exportInfographicAsPng(model, filename);
    }
    return filename;
  } catch (err) {
    console.error(`Infographic ${format.toUpperCase()} Generation Error:`, err);
    throw err;
  }
};

